const fs = require('fs');
const lines = [
"\"use client\"",
"",
"import { useState } from \"react\"",
"import { ArrowRightLight, ClipboardCheck } from \"lucide-react\"",
"import { useAsyncLoad } from \"@/shared/use-async-load\"",
"import { PanelHead, Section, EmptyState, input, fieldWrap, fieldLabel, btnPrimary, tabOn, tabOff, alertError, badgeSolid, th, td } from \"@/shared/components/ui\"",
"",
'type Row = Record<string, unknown>',
'type InventoryData = { stock: Row[]; movements: Row[]; products: Row[]; warehouses: Row[]; alerts: Row[] }',
'',
'async function parse(response: Response) {',
'  const value = await response.json()',
'  if (!response.ok) throw new Error(value.error?.message ?? "No se pudo completar.")',
'  return value',
'}',
'',
'const child = (row: Row, key: string, name: string) =>',
'  row[key] && typeof row[key] === "object" ? String((row[key] as Row)[name] ?? "—") : "—"',
'',
'export function InventoryPanel() {',
'  const [data, setData] = useState<InventoryData>({ stock: [], movements: [], products: [], warehouses: [], alerts: [] })',
'  const [mode, setMode] = useState<"transfer" | "adjust">("transfer")',
'  const [error, setError] = useState<string>()',
'  const [busy, setBusy] = useState(false)',
'',
'  async function load() {',
'    try {',
'      setData(await parse(await fetch("/api/inventory", { cache: "no-store" })))',
'    } catch (reason) {',
'      setError(reason instanceof Error ? reason.message : "Error")',
'    }',
'  }',
'  useAsyncLoad(load)',
'',
'  async function submit(event: React.FormEvent<HTMLFormElement>) {',
'    event.preventDefault()',
'    setBusy(true)',
'    setError(undefined)',
'    const values = Object.fromEntries(new FormData(event.currentTarget))',
'    const command = mode === "transfer" ? "inventory.transfer" : "inventory.adjust"',
'    const payload =',
'      mode === "transfer"',
'        ? { productId: values.productId, fromWarehouseId: values.fromWarehouseId, toWarehouseId: values.toWarehouseId, quantity: Number(values.quantity), reason: values.reason }',
'        : { productId: values.productId, warehouseId: values.warehouseId, physical: Number(values.physical), reason: values.reason }',
'    try {',
'      await parse(',
'        await fetch("/api/commands", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ command, idempotencyKey: crypto.randomUUID(), data: payload }) }),',
'      )',
'      event.currentTarget.reset()',
'      await load()',
'    } catch (reason) {',
'      setError(reason instanceof Error ? reason.message : "Error")',
'    } finally {',
'      setBusy(false)',
'    }',
'  }',
'',
'  return (',
'    <>',
'      <PanelHead title="Control de inventario" description="Disponibilidad, alertas, transferencias, ajustes y kardex." />',
'      {data.alerts.length > 0 && (',
'        <Section title="Alertas de stock" hint="Productos por debajo del stock mínimo." action={<span className={badgeSolid}>{data.alerts.length}</span>} flush>',
'          <ul className="space-y-1">',
'            {data.alerts.slice(0, 6).map((item) => (',
'              <li key={String(item.id)} className="text-sm text-zinc-700 dark:text-zinc-300">',
'                {child(item, "product", "name")} · {child(item, "warehouse", "name")} · disponible{" "}',
'                {Number(item.physical) - Number(item.reserved)}',
'              </li>',
'            ))}',
'          </ul>',
'        </Section>',
'      )}',
'      <Section title="Movimiento de inventario" hint="Transferir entre almacenes o ajustar existencias.">',
'        <div className="flex gap-2">',
'          <button className={mode === "transfer" ? tabOn : tabOff} onClick={() => setMode("transfer")} type="button">',
'            <ArrowRightLight size={15} /> Transferir',
'          </button>',
'          <button className={mode === "adjust" ? tabOn : tabOff} onClick={() => setMode("adjust")} type="button">',
'            <ClipboardCheck size={15} /> Ajustar / contar',
'          </button>',
'        </div>',
'        <form onSubmit={submit}>',
'          <div className="flex flex-wrap gap-4">',
'            <Select name="productId" label="Producto" rows={data.products} />',
'            {mode === "transfer" ? (',
'              <>',
'                <Select name="fromWarehouseId" label="Desde" rows={data.warehouses} />',
'                <Select name="toWarehouseId" label="Hacia" rows={data.warehouses} />',
'                <NumberField name="quantity" label="Cantidad" />',
'              </>',
'            ) : (',
'              <>',
'                <Select name="warehouseId" label="Almacén" rows={data.warehouses} />',
'                <NumberField name="physical" label="Existencia física contada" />',
'              </>',
'            )}',
'          </div>',
'          <div className={fieldWrap}>',
'            <label htmlFor="inventory-reason" className={fieldLabel}>Motivo obligatorio</label>',
'            <input className={input} id="inventory-reason" name="reason" minLength={8} required />',
'          </div>',
'          {error && <div className={alertError}>{error}</div>}',
'          <button className={btnPrimary} disabled={busy}>',
'            {busy ? "Procesando…" : mode === "transfer" ? "Registrar transferencia" : "Registrar ajuste"}',
'          </button>',
'        </form>',
'      </Section>',
'      <Section title="Kardex reciente" hint="Promedio ponderado como método de valoración">',
'        {data.movements.length === 0 ? (',
'          <EmptyState message="Sin movimientos registrados aún." />',
'        ) : (',
'          <div className="overflow-x-auto">',
'            <table className="w-full text-left text-sm">',
'              <thead>',
'                <tr>',
'                  <th className={th}>Fecha</th>',
'                  <th className={th}>Producto</th>',
'                  <th className={th}>Almacén</th>',
'                  <th className={th}>Tipo</th>',
'                  <th className={th}>Cantidad</th>',
'                  <th className={th}>Anterior</th>',
'                  <th className={th}>Posterior</th>',
'                  <th className={th}>Motivo</th>',
'                </tr>',
'              </thead>',
'              <tbody>',
'                {data.movements.map((row) => (',
'                  <tr key={String(row.id)}>',
'                    <td className={td}>{new Date(String(row.createdAt)).toLocaleString("es-PE")}</td>',
'                    <td className={td}>{child(row, "product", "name")}</td>',
'                    <td className={td}>{child(row, "warehouse", "name")}</td>',
'                    <td className={td}>',
'                      <span className={badgeSolid}>{String(row.type)}</span>',
'                    </td>',
'                    <td className={td}>{String(row.quantity)}</td>',
'                    <td className={td}>{String(row.previous)}</td>',
'                    <td className={td}>{String(row.resulting)}</td>',
'                    <td className={td}>{String(row.reason)}</td>',
'                  </tr>',
'                ))}',
'              </tbody>',
'            </table>',
'          </div>',
'        )}',
'      </Section>',
'    </>',
'  )',
'}',
'',
'function Select({ name, label, rows }: { name: string; label: string; rows: Row[] }) {',
'  return (',
'    <div className={fieldWrap} style={{ flex: 1, minWidth: 180 }}>',
'      <label htmlFor={name} className={fieldLabel}>{label}</label>',
'      <select className={input} id={name} name={name} required>',
'        <option value="">Seleccionar</option>',
'        {rows.map((row) => (',
'          <option key={String(row.id)} value={String(row.id)}>',
'            {String(row.name)} {row.sku ? `(${String(row.sku)})` : ""}',
'          </option>',
'        ))}',
'      </select>',
'    </div>',
'  )',
'}',
'',
'function NumberField({ name, label }: { name: string; label: string }) {',
'  return (',
'    <div className={fieldWrap} style={{ flex: 1, minWidth: 150 }}>',
'      <label htmlFor={name} className={fieldLabel}>{label}</label>',
'      <input className={input} id={name} name={name} type="number" min="0.0001" step="0.0001" required />',
'    </div>',
'  )',
'}',
'',
].join("\n");
const content = lines.join("\n");
fs.writeFileSync("src/components/inventory-panel.tsx", content, "utf8");
console.log("File written successfully");
